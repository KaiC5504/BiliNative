"""Writes ios/Generated/AppKeys.swift from the BILI_APP_KEYS secret ("<appkey>:<appsec>").

The pair is Bilibili's public TV-client key, kept out of the repo on purpose. Without the
variable (forks, the PC) or with a malformed one the file holds nil, so every build still
compiles and the app just hides what needs the keys. Never prints the values: they are
masked first, and the public Actions log is the one place they could leak.
"""

import os
import sys

NIL_SOURCE = """// Generated by tools/write_app_keys.py. Gitignored; never commit it.
enum AppKeys {
    static let tv: (key: String, secret: String)? = nil
}
"""

KEYS_SOURCE = """// Generated by tools/write_app_keys.py. Gitignored; never commit it.
enum AppKeys {{
    static let tv: (key: String, secret: String)? = ("{key}", "{secret}")
}}
"""


def swift_literal(text):
    return text.replace("\\", "\\\\").replace('"', '\\"')


def parse(value):
    """Returns (key, secret), or None when the value is not a usable pair."""
    key, colon, secret = value.partition(":")
    key, secret = key.strip(), secret.strip()
    if not colon or not key or not secret:
        return None
    # A control character would break the ::add-mask:: command and could inject others.
    if any(ord(char) < 32 or ord(char) == 127 for char in key + secret):
        return None
    return key, secret


def write(out_path, source):
    directory = os.path.dirname(out_path)
    if directory:
        os.makedirs(directory, exist_ok=True)
    with open(out_path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(source)


def main(out_path, env=os.environ):
    value = env.get("BILI_APP_KEYS", "")
    pair = parse(value) if value.strip() else None
    if pair is None:
        write(out_path, NIL_SOURCE)
        reason = "malformed (expected appkey:appsec)" if value.strip() else "not set"
        print(f"::notice::BILI_APP_KEYS is {reason}; building without app keys, so the dislike button stays greyed out.")
        return 0
    key, secret = pair
    for half in (key, secret):
        print(f"::add-mask::{half}")
    for half in (key, secret):
        escaped = swift_literal(half)
        if escaped != half:
            print(f"::add-mask::{escaped}")
    write(out_path, KEYS_SOURCE.format(key=swift_literal(key), secret=swift_literal(secret)))
    print("app keys written")
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit("usage: write_app_keys.py <AppKeys.swift path>")
    sys.exit(main(sys.argv[1]))
